-- ---------- Compute + storage objects ----------
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS AGRI_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS AGRIFRESH;

CREATE SCHEMA IF NOT EXISTS AGRIFRESH.RAW;     -- landing: COPY INTO target, all VARCHAR
CREATE SCHEMA IF NOT EXISTS AGRIFRESH.BRONZE;  -- dbt: 1:1 copy of raw + audit columns
CREATE SCHEMA IF NOT EXISTS AGRIFRESH.SILVER;  -- dbt: typed, cleaned, deduplicated, tested
CREATE SCHEMA IF NOT EXISTS AGRIFRESH.GOLD;    -- dbt: star schema (dims + facts) for reporting

-- ---------- Roles ----------
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS LOADER;       -- loads CSV files into RAW
CREATE ROLE IF NOT EXISTS TRANSFORMER;  -- dbt runs as this role

GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE AGRI_WH TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE AGRI_WH TO ROLE TRANSFORMER;

GRANT USAGE ON DATABASE AGRIFRESH TO ROLE LOADER;
GRANT USAGE ON DATABASE AGRIFRESH TO ROLE TRANSFORMER;

-- LOADER owns what lands in RAW
GRANT ALL PRIVILEGES ON SCHEMA AGRIFRESH.RAW TO ROLE LOADER;

-- TRANSFORMER reads RAW, builds BRONZE + SILVER + GOLD
GRANT USAGE ON SCHEMA AGRIFRESH.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA AGRIFRESH.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AGRIFRESH.RAW TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA AGRIFRESH.BRONZE TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA AGRIFRESH.SILVER TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA AGRIFRESH.GOLD   TO ROLE TRANSFORMER;

-- ---------- Give your user both roles ----------
GRANT ROLE LOADER      TO USER <YOUR_USER>;
GRANT ROLE TRANSFORMER TO USER <YOUR_USER>;
