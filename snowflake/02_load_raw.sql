-- =====================================================================
-- AgriFresh DWH - load the 13 source CSVs into AGRIFRESH.RAW
-- Every column lands as VARCHAR so nothing is rejected at load time;
-- typing and cleaning happen in dbt (SILVER).
--
-- PUT only works from SnowSQL / Snowflake CLI (`snow sql`), not Snowsight.
-- In Snowsight, upload the files to the stage via Data > Add Data instead,
-- then run everything except the PUT line.
-- =====================================================================

USE ROLE LOADER;
USE WAREHOUSE AGRI_WH;
USE SCHEMA AGRIFRESH.RAW;

CREATE FILE FORMAT IF NOT EXISTS CSV_FORMAT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('')
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = FALSE          -- keep raw values as-is; trimming is a SILVER concern
  ENCODING = 'UTF8';

CREATE STAGE IF NOT EXISTS AGRIFRESH_STAGE
  FILE_FORMAT = CSV_FORMAT;

-- Absolute path to this project's data/ folder (adjust if you move the project)
PUT file:///Users/abdelrahmantarek/agrifresh_dwh/data/*.csv @AGRIFRESH_STAGE AUTO_COMPRESS = TRUE OVERWRITE = TRUE;


-- ---------- regions ----------
CREATE TABLE IF NOT EXISTS REGIONS (
  REGION_ID VARCHAR,
  REGION_CODE VARCHAR,
  REGION_NAME VARCHAR,
  COUNTRY VARCHAR,
  CURRENCY_CODE VARCHAR,
  _SOURCE_FILE VARCHAR,
  _LOADED_AT TIMESTAMP_LTZ
);
COPY INTO REGIONS (REGION_ID, REGION_CODE, REGION_NAME, COUNTRY, CURRENCY_CODE, _SOURCE_FILE, _LOADED_AT)
FROM (
  SELECT t.$1, t.$2, t.$3, t.$4, t.$5,
         METADATA$FILENAME, CURRENT_TIMESTAMP()
  FROM @AGRIFRESH_STAGE/regions.csv t
)
ON_ERROR = 'ABORT_STATEMENT';

